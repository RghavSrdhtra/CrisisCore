// User Privilege Levels & Role Definitions (Per Section 4.1, 4.7, 4.8, 4.11)

export const ROLES = {
  CIVILIAN: 'CIVILIAN',
  RESPONDER: 'RESPONDER',
  COORDINATOR: 'COORDINATOR',
  ADMIN: 'ADMIN'
};

export const PERMISSIONS = {
  // Civilian capabilities
  SUBMIT_SOS: [ROLES.CIVILIAN, ROLES.ADMIN],
  VIEW_OWN_SOS: [ROLES.CIVILIAN, ROLES.ADMIN],
  TOGGLE_LOCATION_SHARING: [ROLES.CIVILIAN, ROLES.ADMIN],

  // Responder capabilities
  VIEW_ASSIGNED_INCIDENTS: [ROLES.RESPONDER, ROLES.COORDINATOR, ROLES.ADMIN],
  UPDATE_RESPONDER_STATUS: [ROLES.RESPONDER, ROLES.COORDINATOR, ROLES.ADMIN],
  REQUEST_BACKUP: [ROLES.RESPONDER, ROLES.ADMIN],

  // Coordinator capabilities
  VIEW_ALL_INCIDENTS: [ROLES.COORDINATOR, ROLES.ADMIN],
  VIEW_ALL_RESPONDERS: [ROLES.COORDINATOR, ROLES.ADMIN],
  DISPATCH_ASSIGNMENT: [ROLES.COORDINATOR, ROLES.ADMIN],
  OVERRIDE_PRIORITY: [ROLES.COORDINATOR, ROLES.ADMIN],
  RESOLVE_INCIDENT: [ROLES.COORDINATOR, ROLES.ADMIN],
  VIEW_TACTICAL_MAP: [ROLES.COORDINATOR, ROLES.ADMIN],

  // Admin capabilities
  MANAGE_USERS: [ROLES.ADMIN],
  MANAGE_FLEET: [ROLES.ADMIN],
  VIEW_AUDIT_LOGS: [ROLES.ADMIN],
  PURGE_LOCATION_DATA: [ROLES.ADMIN]
};

export const hasPermission = (userRole, permissionKey) => {
  const allowedRoles = PERMISSIONS[permissionKey];
  return allowedRoles ? allowedRoles.includes(userRole) : false;
};
